package com.mugsun.boot.common.crypto;

import com.mugsun.core.web.crypto.ApiCryptoService;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.test.util.ReflectionTestUtils;

import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermissions;

import static org.assertj.core.api.Assertions.assertThat;

/** 审计签名密钥：没配时自动生成并持久化（strict-keys 也不拒绝），重启复用，与接口密钥分文件 */
class GmCryptoSignKeyTest {

	@TempDir
	Path home;

	private GmCryptoConfig config(boolean strict) {
		GmCryptoConfig c = new GmCryptoConfig();
		ReflectionTestUtils.setField(c, "gmEnabled", true);
		ReflectionTestUtils.setField(c, "home", home.toString());
		ReflectionTestUtils.setField(c, "strictKeys", false);
		ReflectionTestUtils.setField(c, "signPrivateKey", "");
		ReflectionTestUtils.setField(c, "signPublicKey", "");
		// SM2 传输密钥 strict 下仍要求注入（不在本次范围）；这里 strict 只验签名侧不再拒绝
		if (strict) {
			String[] pair = Sm2Util.generateKeyPair();
			ReflectionTestUtils.setField(c, "sm2PrivateKey", pair[0]);
			ReflectionTestUtils.setField(c, "sm2PublicKey", pair[1]);
			ReflectionTestUtils.setField(c, "strictKeys", true);
		}
		return c;
	}

	@Test
	@DisplayName("strict-keys=true 且没配签名密钥：不拒绝启动，生成文件 600，重启复用同一把")
	void autoGeneratedAndReused() throws Exception {
		GmCryptoConfig first = config(true);
		first.init();
		Path f = home.resolve(GmCryptoConfig.SIGN_KEY_FILE);
		assertThat(first.signKeyFile()).isEqualTo(f);
		String content = Files.readString(f);
		if (Files.getFileStore(f).supportsFileAttributeView("posix")) {
			assertThat(PosixFilePermissions.toString(Files.getPosixFilePermissions(f))).isEqualTo("rw-------");
		}
		GmCryptoConfig second = config(false);
		second.init();
		assertThat(Files.readString(f)).isEqualTo(content);
		assertThat(GmCryptoConfig.SIGN_KEY_FILE).isNotEqualTo(ApiCryptoService.LOCAL_KEY_FILE);
	}
}
