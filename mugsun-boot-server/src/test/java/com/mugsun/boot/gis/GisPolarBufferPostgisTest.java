package com.mugsun.boot.gis;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.mugsun.boot.gis.entity.GisLayer;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.locationtech.jts.geom.Coordinate;
import org.locationtech.jts.geom.Geometry;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.utility.DockerImageName;

import javax.sql.DataSource;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * mugsun-boot#63：识别极冠（AMBIGUOUS）；geography ST_Buffer 会丢极冠；
 * {@link GisSpatialQueryService#buffer} 对 AMBIGUOUS 行改走 JVM 极点 AEQD，结果仍含极冠。
 */
class GisPolarBufferPostgisTest {

	private static final String NORTH_CAP =
		"POLYGON((-180 80, -90 80, 0 80, 90 80, 180 80, 180 90, -180 90, -180 80))";
	private static final String SOUTH_CAP =
		"POLYGON((-180 -80, -90 -80, 0 -80, 90 -80, 180 -80, 180 -90, -180 -90, -180 -80))";

	private static PostgreSQLContainer<?> postgis;
	private static DataSource dataSource;
	private static JdbcTemplate jdbc;
	private static GisSpatialQueryService service;
	private static GisGeometryCodec codec;

	@BeforeAll
	static void startDb() {
		postgis = new PostgreSQLContainer<>(
			DockerImageName.parse("postgis/postgis:16-3.4").asCompatibleSubstituteFor("postgres"))
			.withDatabaseName("mugsun").withUsername("mugsun").withPassword("mugsun");
		postgis.start();
		DriverManagerDataSource ds = new DriverManagerDataSource(
			postgis.getJdbcUrl(), postgis.getUsername(), postgis.getPassword());
		ds.setDriverClassName("org.postgresql.Driver");
		dataSource = ds;
		jdbc = new JdbcTemplate(ds);
		jdbc.execute("CREATE EXTENSION IF NOT EXISTS postgis");
		jdbc.execute("""
			CREATE TABLE gis_feature (
				id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
				tenant_id    VARCHAR(12),
				layer_id     BIGINT NOT NULL,
				geom         geometry(Geometry, 4326) NOT NULL,
				props_json   TEXT,
				create_time  TIMESTAMP,
				update_time  TIMESTAMP,
				wraps_antimeridian boolean GENERATED ALWAYS AS (
					(ST_XMax(geom) - ST_XMin(geom) > 180)
					AND (ST_XMax(ST_ShiftLongitude(geom)) - ST_XMin(ST_ShiftLongitude(geom)) <= 180)
				) STORED NOT NULL,
				is_deleted   INT NOT NULL DEFAULT 0
			)
			""");
		GisSpatialSupport support = new GisSpatialSupport(dataSource);
		support.reset();
		ObjectMapper om = new ObjectMapper();
		GisFeatureStore store = new GisFeatureStore(support, om);
		codec = new GisGeometryCodec();
		service = new GisSpatialQueryService(support, store, codec, om);
	}

	@AfterAll
	static void stopDb() {
		if (postgis != null) {
			postgis.stop();
		}
	}

	private static boolean ambiguous(String wkt) {
		return Boolean.TRUE.equals(jdbc.queryForObject("SELECT " + GisSpatialQueryService.AMBIGUOUS
			+ " FROM (SELECT ST_GeomFromText(?, 4326) AS geom) t", Boolean.class, wkt));
	}

	private static GisLayer layerWithCap(long layerId, String wkt, String name) {
		jdbc.update("DELETE FROM gis_feature WHERE layer_id = ?", layerId);
		jdbc.update("""
			INSERT INTO gis_feature (tenant_id, layer_id, geom, props_json, create_time, update_time, is_deleted)
			VALUES ('0', ?, ST_GeomFromText(?, 4326), ?, now(), now(), 0)
			""", layerId, wkt, "{\"name\":\"" + name + "\"}");
		GisLayer layer = new GisLayer();
		layer.setId(layerId);
		layer.setTenantId("0");
		layer.setKind(GisConstants.KIND_VECTOR);
		layer.setFeatureCount(1);
		return layer;
	}

	@Test
	@DisplayName("极冠判为走向不确定；跨 180° 线、普通面、极点附近的点不算")
	void classify() {
		assertThat(ambiguous(NORTH_CAP)).isTrue();
		assertThat(ambiguous(SOUTH_CAP)).isTrue();
		assertThat(ambiguous("LINESTRING(179.9 0, -179.9 0)")).isFalse();
		assertThat(ambiguous("POLYGON((116 39, 117 39, 117 40, 116 40, 116 39))")).isFalse();
		assertThat(ambiguous("POINT(0 89.99)")).isFalse();
		// 佐证：geography 缓冲确实丢了极冠（结果最北不到 80°N）
		Double maxLat = jdbc.queryForObject(
			"SELECT ST_YMax(ST_Buffer(ST_GeomFromText(?, 4326)::geography, 1000)::geometry)",
			Double.class, NORTH_CAP);
		assertThat(maxLat).isLessThan(85d);
	}

	@Test
	@DisplayName("SpatialQueryService：AMBIGUOUS 极冠走 JVM 极点 AEQD，缓冲仍含极冠且边界纬合理")
	@SuppressWarnings("unchecked")
	void serviceAmbiguousFallsBackToJvmPolarAeqd() {
		GisLayer layer = layerWithCap(63L, NORTH_CAP, "north-cap");
		Map<String, Object> out = service.buffer(layer, 1000d, 10, false);
		assertThat(out.get("engine")).isEqualTo(GisConstants.ENGINE_POSTGIS);
		assertThat(out.get("skipped")).isEqualTo(0);
		List<Map<String, Object>> feats = (List<Map<String, Object>>) out.get("features");
		assertThat(feats).hasSize(1);
		Geometry buf = codec.fromGeometry((Map<?, ?>) feats.get(0).get("geometry"));
		assertThat(GisGeodesic.enclosedPole(buf)).isEqualTo(1);
		var gf = new org.locationtech.jts.geom.GeometryFactory();
		assertThat(buf.covers(gf.createPoint(new Coordinate(0, 90)))).isTrue();
		assertThat(buf.covers(gf.createPoint(new Coordinate(0, 85)))).isTrue();
		double minY = buf.getEnvelopeInternal().getMinY();
		assertThat(minY).isLessThan(80d);
		assertThat(minY).isGreaterThan(79.98d);
	}

	@Test
	@DisplayName("SpatialQueryService：南极 AMBIGUOUS 同样走 JVM，缓冲仍含南极冠")
	@SuppressWarnings("unchecked")
	void serviceSouthCapJvmPolarAeqd() {
		GisLayer layer = layerWithCap(64L, SOUTH_CAP, "south-cap");
		Map<String, Object> out = service.buffer(layer, 1000d, 10, false);
		assertThat(out.get("skipped")).isEqualTo(0);
		List<Map<String, Object>> feats = (List<Map<String, Object>>) out.get("features");
		assertThat(feats).hasSize(1);
		Geometry buf = codec.fromGeometry((Map<?, ?>) feats.get(0).get("geometry"));
		assertThat(GisGeodesic.enclosedPole(buf)).isEqualTo(-1);
		assertThat(buf.covers(new org.locationtech.jts.geom.GeometryFactory()
			.createPoint(new Coordinate(0, -90)))).isTrue();
		double maxY = buf.getEnvelopeInternal().getMaxY();
		assertThat(maxY).isGreaterThan(-80d);
		assertThat(maxY).isLessThan(-79.98d);
	}
}
