package com.mugsun.boot.gis;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.mugsun.boot.gis.entity.GisLayer;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.utility.DockerImageName;

import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

/**
 * mugsun-boot#64：走 GisSpatialQueryService（真实 PostGIS + GisFeatureStore 入库）验证存量跨 180° 要素的
 * 半径、最近邻；两条路径（postgis / forceJava）同一组断言，含 Java 路径从 (0, 0) 查 180° 附近的面不再是 0 米。
 */
class GisStoredAntimeridianServiceTest {

	private static final long LAYER_ID = 900064L;
	private static PostgreSQLContainer<?> postgis;
	private static GisSpatialQueryService service;
	private static GisLayer layer;

	@BeforeAll
	static void startDb() {
		postgis = new PostgreSQLContainer<>(
			DockerImageName.parse("postgis/postgis:16-3.4").asCompatibleSubstituteFor("postgres"))
			.withDatabaseName("mugsun").withUsername("mugsun").withPassword("mugsun");
		postgis.start();
		DriverManagerDataSource ds = new DriverManagerDataSource(
			postgis.getJdbcUrl(), postgis.getUsername(), postgis.getPassword());
		ds.setDriverClassName("org.postgresql.Driver");
		JdbcTemplate jdbc = new JdbcTemplate(ds);
		jdbc.execute("CREATE EXTENSION IF NOT EXISTS postgis");
		jdbc.execute("""
			CREATE TABLE gis_feature (
				id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
				tenant_id   VARCHAR(12),
				layer_id    BIGINT NOT NULL,
				geom        geometry(Geometry, 4326) NOT NULL,
				props_json  TEXT,
				create_time TIMESTAMP,
				update_time TIMESTAMP,
				is_deleted  INT NOT NULL DEFAULT 0
			)
			""");
		jdbc.execute("CREATE INDEX idx_gis_feature_geom ON gis_feature USING GIST (geom)");
		GisSpatialSupport support = mock(GisSpatialSupport.class);
		when(support.available()).thenReturn(true);
		when(support.jdbc()).thenReturn(jdbc);
		ObjectMapper om = new ObjectMapper();
		GisFeatureStore store = new GisFeatureStore(support, om);
		service = new GisSpatialQueryService(support, store, new GisGeometryCodec(), om);
		String data = "{\"type\":\"FeatureCollection\",\"features\":["
			+ "{\"type\":\"Feature\",\"id\":\"l\",\"properties\":{\"k\":\"am-line\"},\"geometry\":{\"type\":\"LineString\",\"coordinates\":[[179.9,0],[-179.9,0]]}},"
			+ "{\"type\":\"Feature\",\"id\":\"p\",\"properties\":{\"k\":\"am-poly\"},\"geometry\":{\"type\":\"Polygon\",\"coordinates\":[[[179,-1],[-179,-1],[-179,1],[179,1],[179,-1]]]}},"
			+ "{\"type\":\"Feature\",\"id\":\"e\",\"properties\":{\"k\":\"east\"},\"geometry\":{\"type\":\"Point\",\"coordinates\":[179.99,0.5]}},"
			+ "{\"type\":\"Feature\",\"id\":\"f\",\"properties\":{\"k\":\"far\"},\"geometry\":{\"type\":\"Point\",\"coordinates\":[100,50]}}]}";
		store.sync(LAYER_ID, "000000", GisConstants.KIND_VECTOR, data);
		layer = new GisLayer();
		layer.setId(LAYER_ID);
		layer.setTenantId("000000");
		layer.setKind(GisConstants.KIND_VECTOR);
		layer.setDataJson(data);
		layer.setFeatureCount(4);
	}

	@AfterAll
	static void stopDb() {
		if (postgis != null) {
			postgis.stop();
		}
	}

	@SuppressWarnings("unchecked")
	private static List<String> keys(Map<String, Object> out) {
		return ((List<Map<String, Object>>) out.get("features")).stream()
			.map(f -> String.valueOf(((Map<String, Object>) f.get("properties")).get("k"))).toList();
	}

	@ParameterizedTest(name = "forceJava={0}")
	@ValueSource(booleans = { false, true })
	@DisplayName("半径：180° 两侧都能查到，(0, 0) 不误命中")
	void radius(boolean forceJava) {
		Map<String, Object> near = service.radius(layer, -179.95, 0.1, 60_000d, 10, forceJava);
		assertThat(near.get("engine")).isEqualTo(forceJava ? "java" : "postgis");
		assertThat(keys(near)).containsExactlyInAnyOrder("am-line", "am-poly", "east");
		assertThat(keys(service.radius(layer, 0, 0, 100_000d, 10, forceJava))).isEmpty();
	}

	@ParameterizedTest(name = "forceJava={0}")
	@ValueSource(booleans = { false, true })
	@DisplayName("最近邻：按地面距离排序，180° 对岸的点与跨 180° 要素排在远点前面")
	void nearest(boolean forceJava) {
		Map<String, Object> out = service.nearest(layer, -179.98, 0.5, 3, forceJava);
		assertThat(keys(out)).hasSize(3).doesNotContain("far");
		assertThat(keys(out).get(0)).isIn("am-poly", "east");
	}

	@ParameterizedTest(name = "forceJava={0}")
	@ValueSource(booleans = { false, true })
	@DisplayName("从 (0, 0) 查 180° 附近的面：距离约 2 万公里而不是 0 米")
	@SuppressWarnings("unchecked")
	void farPolygonNotZero(boolean forceJava) {
		Map<String, Object> out = service.nearest(layer, 0, 0, 4, forceJava);
		Map<String, Object> poly = ((List<Map<String, Object>>) out.get("features")).stream()
			.filter(f -> "am-poly".equals(((Map<String, Object>) f.get("properties")).get("k"))).findFirst().orElseThrow();
		double meters = ((Number) ((Map<String, Object>) poly.get("properties")).get("meters")).doubleValue();
		assertThat(meters).isGreaterThan(19_000_000d);
	}
}
