-- 历史 track_stats_day UV 回填（distinct_id 口径，见 0.1.x 升级说明）：回填前备份被改动行的旧 UV。
-- 只新增表，不改已发布的 T1。
CREATE TABLE IF NOT EXISTS track_stats_day_uv_backup (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        VARCHAR(40)  NOT NULL,
    stats_day_id  BIGINT       NOT NULL,
    app_key       VARCHAR(32)  NOT NULL,
    stat_date     DATE         NOT NULL,
    dim_type      VARCHAR(16)  NOT NULL,
    dim_key       VARCHAR(255) NOT NULL,
    old_uv        BIGINT       NOT NULL,
    new_uv        BIGINT       NOT NULL,
    backup_time   TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_uv_backup_run ON track_stats_day_uv_backup (run_id);
CREATE INDEX IF NOT EXISTS idx_uv_backup_day ON track_stats_day_uv_backup (app_key, stat_date);
COMMENT ON TABLE track_stats_day_uv_backup IS 'track_stats_day UV 回填备份：每次回填改动前的旧值（按 run_id 可整批还原）';
COMMENT ON COLUMN track_stats_day_uv_backup.run_id IS '回填批次标识';
COMMENT ON COLUMN track_stats_day_uv_backup.stats_day_id IS 'track_stats_day.id';
COMMENT ON COLUMN track_stats_day_uv_backup.old_uv IS '回填前 UV';
COMMENT ON COLUMN track_stats_day_uv_backup.new_uv IS '回填后 UV（distinct_id 口径）';
